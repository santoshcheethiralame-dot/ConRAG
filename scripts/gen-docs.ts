// Generates docs/DATA-DICTIONARY.md and docs/QUERIES.md from the live database (run after demo:load).
//   npm run docs
import { readFileSync, writeFileSync } from "node:fs";
import { Client } from "pg";
import { parseQueryPack } from "./lib/querypack";

const cell = (v: unknown) => String(v ?? "").replace(/\|/g, "\\|").replace(/\s+/g, " ").trim();
const table = (head: string[], rows: unknown[][]) =>
  [`| ${head.join(" | ")} |`, `|${head.map(() => "---").join("|")}|`, ...rows.map((r) => `| ${r.map(cell).join(" | ")} |`)].join("\n");

async function main() {
  const url = process.env.DATABASE_URL;
  if (!url) throw new Error("DATABASE_URL is not set");
  const db = new Client({ connectionString: url });
  await db.connect();
  const q = async (sql: string) => (await db.query(sql)).rows;

  /* ---------- data dictionary ---------- */
  const tables = (await q(`SELECT c.oid, c.relname FROM pg_class c WHERE c.relnamespace = 'public'::regnamespace AND c.relkind = 'r' AND c.relname <> 'schema_migrations' ORDER BY c.relname`)) as { oid: number; relname: string }[];
  let dd = `# Data dictionary

Generated from the live schema by \`npm run docs\` (do not edit by hand). Narrative design, the ER diagram and the justification for each store are in [er-diagram.md](er-diagram.md) and [DESIGN.md](DESIGN.md).

Types use PostgreSQL names; \`vector(384)\` is pgvector. \`bigint identity\` columns are generated by the database.

`;
  for (const t of tables) {
    const cols = await q(`SELECT a.attname, format_type(a.atttypid, a.atttypmod) AS type, a.attnotnull, a.attgenerated, pg_get_expr(d.adbin, d.adrelid) AS def, a.attidentity
      FROM pg_attribute a LEFT JOIN pg_attrdef d ON d.adrelid = a.attrelid AND d.adnum = a.attnum
      WHERE a.attrelid = ${t.oid} AND a.attnum > 0 AND NOT a.attisdropped ORDER BY a.attnum`);
    const cons = await q(`SELECT conname, contype, pg_get_constraintdef(oid) AS def FROM pg_constraint WHERE conrelid = ${t.oid} ORDER BY contype DESC, conname`);
    const idx = await q(`SELECT indexname, indexdef FROM pg_indexes WHERE schemaname = 'public' AND tablename = '${t.relname}' ORDER BY indexname`);
    const trg = await q(`SELECT tgname, pg_get_triggerdef(oid) AS def FROM pg_trigger WHERE tgrelid = ${t.oid} AND NOT tgisinternal ORDER BY tgname`);
    const kind: Record<string, string> = { p: "PRIMARY KEY", f: "FOREIGN KEY", u: "UNIQUE", c: "CHECK" };
    dd += `## ${t.relname}\n\n`;
    dd += table(
      ["Column", "Type", "Null", "Default / generated"],
      cols.map((c) => [
        c.attname,
        c.type,
        c.attnotnull ? "no" : "yes",
        c.attidentity ? "identity" : c.attgenerated ? `generated: ${c.def}` : (c.def ?? ""),
      ]),
    );
    dd += `\n\n**Constraints**\n\n` + table(["Name", "Kind", "Definition"], cons.map((c) => [c.conname, kind[c.contype] ?? c.contype, c.def]));
    dd += `\n\n**Indexes**\n\n` + table(["Name", "Definition"], idx.map((i) => [i.indexname, i.indexdef]));
    if (trg.length) dd += `\n\n**Triggers**\n\n` + table(["Name", "Definition"], trg.map((x) => [x.tgname, x.def]));
    dd += "\n\n";
  }
  const fns = await q(`SELECT p.proname, pg_get_function_arguments(p.oid) AS args, pg_get_function_result(p.oid) AS result, l.lanname
    FROM pg_proc p JOIN pg_language l ON l.oid = p.prolang
    WHERE p.pronamespace = 'public'::regnamespace AND p.prokind = 'f' AND l.lanname IN ('sql', 'plpgsql') ORDER BY p.proname`);
  dd += `## Functions\n\n` + table(["Name", "Arguments", "Returns", "Language"], fns.map((f) => [f.proname, f.args, f.result, f.lanname])) + "\n\n";
  const views = await q(`SELECT viewname FROM pg_views WHERE schemaname = 'public' ORDER BY viewname`);
  dd += `## Views\n\n` + views.map((v) => `- \`${v.viewname}\``).join("\n") + "\n\n";
  const enums = await q(`SELECT t.typname, string_agg(e.enumlabel, ', ' ORDER BY e.enumsortorder) AS labels FROM pg_type t JOIN pg_enum e ON e.enumtypid = t.oid GROUP BY t.typname ORDER BY t.typname`);
  dd += `## Enumerated types\n\n` + table(["Type", "Values"], enums.map((e) => [e.typname, e.labels])) + "\n";
  writeFileSync("docs/DATA-DICTIONARY.md", dd);

  /* ---------- query pack with live output ---------- */
  const blocks = parseQueryPack(readFileSync("db/queries.sql", "utf8"));
  let qd = `# Important queries

Every query below lives in [db/queries.sql](../db/queries.sql), is executed by the test suite (\`tests/queries.test.ts\`), and is rendered here with its real output against the demo data (\`npm run docs\`).

The application's own DML (INSERT / UPDATE / DELETE) is in the route handlers and libraries; the table at the end maps each to its file.

`;
  let n = 0;
  for (const b of blocks) {
    n++;
    const res = await db.query(b.sql);
    const shown = res.rows.slice(0, 8);
    qd += `## ${n}. ${b.name}\n\n*Demonstrates:* ${b.shows}\n\n\`\`\`sql\n${b.sql}\n\`\`\`\n\n`;
    qd += shown.length
      ? table(res.fields.map((f) => f.name), shown.map((r) => res.fields.map((f) => r[f.name]))) + (res.rows.length > 8 ? `\n\n*(${res.rows.length - 8} more rows)*` : "")
      : "*(no rows)*";
    qd += "\n\n";
  }

  qd += `## Index usage\n\nThe planner is steered away from sequential scans (the demo tables are tiny) to show that the indexes are usable for these query shapes.\n\n`;
  await db.query("SET enable_seqscan = off");
  const probe = "(SELECT embedding FROM claims ORDER BY id LIMIT 1)";
  for (const [label, sql] of [
    ["Vector nearest-neighbour (HNSW, cosine)", `EXPLAIN SELECT id FROM claims ORDER BY embedding <=> ${probe} LIMIT 5`],
    ["Full-text match (GIN on tsvector)", `EXPLAIN SELECT id FROM documents WHERE tsv @@ websearch_to_tsquery('english', 'attendance')`],
    ["Open contradictions (partial index)", `EXPLAIN SELECT id FROM claim_relations WHERE relation = 'contradicts'`],
  ]) {
    const plan = (await db.query(sql)).rows.map((r) => r["QUERY PLAN"]).join("\n");
    qd += `**${label}**\n\n\`\`\`\n${plan}\n\`\`\`\n\n`;
  }

  qd += `## Where the application issues DML

${table(
  ["Operation", "Statement", "Where"],
  [
    ["INSERT", "documents, chunks, claims, claim_relations in one transaction", "src/lib/ingest.ts (withTx)"],
    ["INSERT", "queries and query_evidence in one transaction", "src/lib/ask.ts"],
    ["INSERT", "users (register), sources, conflict_resolutions", "src/app/api/auth/register, sources, conflicts/[id]/resolve"],
    ["UPDATE", "claim_relations: dismiss a false alarm", "src/app/api/conflicts/[id]/dismiss/route.ts"],
    ["UPDATE", "sources (trust, kind, name); users (role)", "src/app/api/sources/[id], users/[id]"],
    ["UPDATE", "claims.status via triggers (supersede / reactivate)", "db/migrations/003, 004"],
    ["DELETE", "conflict_resolutions (undo), documents, sources, users", "src/app/api/conflicts/[id]/resolve, documents/[id], sources/[id], users/[id]"],
    ["SELECT", "joins, aggregates, window functions, subqueries", "src/lib/queries.ts, src/lib/ask.ts, db/queries.sql"],
  ],
)}
`;
  writeFileSync("docs/QUERIES.md", qd);
  await db.end();
  console.log(`wrote docs/DATA-DICTIONARY.md (${tables.length} tables) and docs/QUERIES.md (${blocks.length} queries)`);
}
main().catch((e) => {
  console.error(e);
  process.exit(1);
});
